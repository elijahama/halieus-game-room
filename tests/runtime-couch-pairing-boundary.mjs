import assert from "node:assert/strict";
import { CouchPairingRegistry } from "../server/src/platform/couchPairing.mjs";
import { createCouchPairingBoundary } from "../server/src/platform/couchPairingBoundary.mjs";
let time=1000, serial=0, bound=[], blocked=new Set(), fail=false;
const registry=new CouchPairingRegistry({now:()=>time,generateCode:()=> (++serial).toString(16).toUpperCase().padStart(10,"0")});
const handle=createCouchPairingBoundary({registry,authenticate:c=>c.account,eligible:id=>!blocked.has(id),getName:id=>id==="guest"?"Guest display":null,bind:(ctx,pair)=>{if(fail)return false;bound.push(pair);return true;},now:()=>time});
const ctx=(id,source=id,beta=false)=>({account:id?{id,beta}:null,source});
const make=(id)=>handle(ctx(id),"create",{game:"connect-four",matchMode:"casual"});
assert.equal(handle(ctx(null,"x"),"create",{game:"connect-four",matchMode:"casual",accountId:"host"}).ok,false);
assert.equal(handle(ctx("host","host",true),"create",{game:"connect-four",matchMode:"casual"}).ok,false);
assert.equal(handle(ctx("host"),"create",{game:"connect-four",matchMode:"ranked"}).ok,false);
const a=make("host"); assert.equal(a.ok,true);
assert.equal(handle(ctx("host"),"request",{code:a.code}).ok,false);
assert.equal(handle(ctx("guest"),"request",{code:a.code,accountId:"spoof"}).ok,true);
assert.equal(handle(ctx("other"),"inspect",{code:a.code}).ok,false);
assert.deepEqual(handle(ctx("host"),"inspect",{code:a.code}),{ok:true,expiresAt:a.expiresAt,guestName:"Guest display"});
assert.equal(handle(ctx("guest"),"approve",{code:a.code}).ok,false);
assert.deepEqual(handle(ctx("host"),"approve",{code:a.code}),{ok:true,paired:true});
assert.deepEqual(bound,[{hostAccountId:"host",guestAccountId:"guest",game:"connect-four"}]);
assert.equal(handle(ctx("host"),"approve",{code:a.code}).ok,false);
const b=make("host"); handle(ctx("guest"),"request",{code:b.code}); blocked.add("guest");
assert.equal(handle(ctx("host"),"approve",{code:b.code}).ok,false); blocked.clear();
assert.equal(handle(ctx("host"),"approve",{code:b.code}).ok,false);
const c=make("host"); handle(ctx("guest"),"request",{code:c.code}); fail=true;
assert.equal(handle(ctx("host"),"approve",{code:c.code}).ok,false); fail=false;
assert.equal(handle(ctx("host"),"approve",{code:c.code}).ok,false); assert.equal(bound.length,1);
const d=make("host"); assert.equal(handle(ctx("host"),"cancel",{code:d.code}).ok,true);
const limited=createCouchPairingBoundary({registry,authenticate:c=>c.account,eligible:()=>true,getName:()=>null,bind:()=>false,now:()=>time,accountLimit:2,sourceLimit:3});
assert.equal(limited(ctx("a","ip"),"create",{game:"connect-four",matchMode:"casual"}).ok,true);
limited(ctx("a","ip"),"inspect",{code:"invalid"});
assert.equal(limited(ctx("a","ip"),"cancel",{code:"invalid"}).ok,false);
limited(ctx("b","ip"),"inspect",{code:"invalid"});
assert.equal(limited(ctx("c","ip"),"create",{game:"connect-four",matchMode:"casual"}).ok,false);
time+=60000; assert.equal(limited(ctx("c","ip"),"create",{game:"connect-four",matchMode:"casual"}).ok,true);
console.log("Couch pairing boundary passed");
