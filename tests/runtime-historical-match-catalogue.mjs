import assert from "node:assert/strict";
import {projectHistoricalMatches} from "../server/src/platform/match-history.ts";
const player={id:"socket-secret",name:"Atlas",progressionIdentity:{accountId:"account-a",beta:false},hand:["SECRET-CARD"],recoveryKey:"SECRET-KEY"};
const opponent={id:"other",name:"Milo",progressionIdentity:{accountId:"account-b",beta:false}};
const match=(id,at,extra={})=>({sessionId:id,game:"mega-board",status:"completed",finalisedAt:at,state:{ranked:true,winnerPlayerId:player.id,players:[player,opponent],hiddenDeck:["SECRET-DECK"]},...extra});
const records=[match("old",1000),match("new",2000,{game:"spar",state:{matchMode:"casual",players:[player,opponent],winnerPlayerId:opponent.id}}),match("new",2000,{game:"spar"}),match("host",3000,{status:"host-ended"}),match("unverified",4000,{state:{players:[{id:"guest",name:"Atlas"}]}}),match("other-account",5000,{state:{players:[opponent]}})];
const page=projectHistoricalMatches(records,"account-a",{limit:2});
assert.equal(page.total,3);assert.equal(page.nextOffset,2);
assert.equal(page.entries[0].result,"unrecorded");assert.equal(page.entries[1].game,"spar");assert.equal(page.entries[1].result,"loss");
assert.equal(projectHistoricalMatches(records,"account-a",{offset:2,limit:2}).entries[0].result,"win");
assert.equal(projectHistoricalMatches(records,"account-a",{game:"spar"}).total,1);
assert.equal(projectHistoricalMatches(records,"unknown").total,0);
assert.equal(projectHistoricalMatches(records,"account-b").total,4);
assert.equal(page.entries[1].replay,"not-assessed");
assert.equal(page.entries[1].players[0].self,true);
assert.ok(!JSON.stringify(page).match(/SECRET|socket-secret|account-a|account-b|hiddenDeck/));
assert.throws(()=>projectHistoricalMatches(records,""),/Authenticated/);
assert.throws(()=>projectHistoricalMatches(records,"account-a",{limit:101}),/pagination/);
assert.equal(records[0].sessionId,"old","source order unchanged");
console.log("PASS historical catalogue pagination, verified identity, deduplication, private-field exclusion and honest replay availability");
