import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {buildInboxTimeline,inboxUnreadCount} from "../client/src/platform/inboxTimeline.ts";
const social=[{id:"s1",actorId:"contact",displayName:"Alex",kind:"game",title:"Alex entered Mega Board",
 detail:"Lobby",gameId:"mega-board",roomCode:"M123",at:300,read:false}];
const request={id:"r1",senderDisplayName:"B",recipientAccountId:"me",status:"pending",game:"mega-board",gameTitle:"Mega Board",createdAt:150};
const room={id:"invite1",senderDisplayName:"C",game:"mega-board",gameTitle:"Mega Board",roomCode:"M123",createdAt:500};
const guild={key:"guild-message:g1",id:"g1",guildId:"g",guildName:"Guild",senderDisplayName:"D",preview:"Hello",createdAt:400};
const friend={id:"f1",senderDisplayName:"E",senderUsername:"e",createdAt:200};
const invite={id:"g1",guildName:"Guild",senderDisplayName:"F",createdAt:250};
const args={social,requests:[request],roomInvites:[room],guildMessages:[guild],friendRequests:[friend],guildInvites:[invite]};
const sorted=buildInboxTimeline(args);
assert.deepEqual(sorted.map(x=>x.key),["room:invite1","guild-message:g1","social:s1","guild-invite:g1","friend:f1","request:r1"]);
assert.equal(inboxUnreadCount(sorted,new Set(),new Set()),6);
const readKeys=new Set(["room:invite1","guild-invite:g1","friend:f1","request:r1"]);
const guildReads=new Set(["guild-message:g1"]);
assert.equal(inboxUnreadCount(sorted,readKeys,guildReads),1,"Unread social events remain distinct.");
assert.equal(inboxUnreadCount(buildInboxTimeline({...args,social:[{...social[0],read:true}]}),readKeys,guildReads),0);
assert.equal(buildInboxTimeline({...args,requests:[{...request,id:"r2",createdAt:500}]}).slice(0,2).map(x=>x.key).join(":"),"request:r2:room:invite1");
const root=new URL("../",import.meta.url);
const home=readFileSync(new URL("client/src/platform/components/HomeScreen.tsx",root),"utf8");
const account=readFileSync(new URL("server/src/platform/accounts.ts",root),"utf8");
const socialDropdown=readFileSync(new URL("client/src/platform/components/SocialRoomDropdown.tsx",root),"utf8");
assert.match(home,/Mark all as read/);
assert.match(home,/inboxUnreadCount\(inboxTimeline, readInboxKeys, readGuildMessages\)/);
assert.match(home,/socialActivity\.markRead\(\)/);
assert.match(home,/kind:"read",keys:messages/,"Unread guild messages acknowledged server-side.");
assert.match(home,/acknowledgeInboxKeys\(keys\)/,"All actionable items get durable account read receipts.");
assert.match(home,/setReadInboxKeys\(new Set\(result\.keys\)\)/);
assert.match(home,/45_?000|45000/,"Room popup must expire.");
assert.match(home,/!item\.read/,"Read activity never triggers a new room popup.");
assert.match(socialDropdown,/onClick=\{onJoin\}/);
assert.match(socialDropdown,/onClick=\{onWatch\}/);
assert.doesNotMatch(socialDropdown,/created a room/,"Never invent room creator identity.");
assert.match(account,/app\.get\("\/accounts\/inbox\/read"/);
assert.match(account,/app\.post\("\/accounts\/inbox\/read"/);
assert.match(account,/currentSession\(request\)/);
assert.match(account,/store\.inboxReadKeys\[auth\.account\.id\]/);
console.log("PASS chronological inbox across six types, durable read receipts, all-read semantics and 45s authenticated-room popups");
